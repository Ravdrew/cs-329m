"""Generate a draft Has / Does-not-have question set from a reference graph (Q1).

Usage:
    python3 scoring/make_questions.py --reference REF.yaml --ownership OWN.json [--adjudications ADJ.yaml]
        [--extra EXTRA.yaml] [--subsystem "booking subsystem"] [--date YYYY-MM-DD] --out Q.json

Questions, in this order (each block sorted by reference id / pair):
  * has/node        one per reference node
  * has/edge        one per distinct reference pair (reference edges plus adjudicated-true pairs)
  * does_not_have/edge  one per adjudicated-false pair
  * does_not_have/edge  reversal negatives: for each reference pair (x,y) with (y,x) not a reference pair and
                    not adjudicated false, y not a model/external node and x not a model node: "does y ... x?"
  * does_not_have/scope one per distinct out_of_scope reason in ownership, answered by whether the graph lists
                    at least half of that reason's files
  * --extra         hand-written questions appended verbatim; ids are renumbered q001, q002, ...
The output is always marked PROVISIONAL: a person must review the questions before they are final.
The output is reference-derived answer-key material: the script refuses to write it inside the team repo when
the reference lives outside it (override with --allow-in-repo).
"""
import argparse
import datetime
import json
import sys
from pathlib import Path

from score_graph import InputError, as_list, file_entries, leaks_into_repo, load, norm_path, reference_pairs

VERB = {'renders': 'render', 'navigates': 'navigate to', 'calls': 'call', 'reads': 'read', 'writes': 'write',
        'emits': 'emit to', 'uses': 'use'}


def verbs(kinds):
    return ' or '.join(VERB.get(k, k) for k in sorted(kinds)) or 'depend on'


def make(ref, ownership, adj, extra, label, subsystem, date):
    nodes = {n['id']: n for n in ref['nodes']}
    name = lambda r: nodes[r].get('label') or r if r in nodes else r
    kind = lambda r: nodes.get(r, {}).get('kind')
    files = ownership.get('files') or {}
    adj_true = {(x['from'], x['to']) for x in adj if x.get('verdict') is True}
    adj_false = {(x['from'], x['to']) for x in adj if x.get('verdict') is False}
    R, _ = reference_pairs(ref, {}, adj_true)  # raw kinds, for wording
    qs = []
    for r in sorted(nodes):
        owned = [p for p in dict.fromkeys(norm_path(p) for p, _ in file_entries(nodes[r]))
                 if (files.get(p) or {}).get('owner') == r]
        shown = (owned or list(dict.fromkeys(norm_path(p) for p, _ in file_entries(nodes[r]))))[:2]
        qs.append({'polarity': 'has', 'category': 'node', 'check': {'type': 'node', 'ref': r},
                   'text': f"Does the graph have a component for {name(r)}"
                           + (f" (files such as {', '.join(shown)})" if shown else '') + '?',
                   'source': f'reference node {r}'})
    for x, y in sorted(R):
        qs.append({'polarity': 'has', 'category': 'edge', 'check': {'type': 'edge', 'from': x, 'to': y},
                   'text': f'Does {name(x)} {verbs(R[(x, y)])} {name(y)}?',
                   'source': 'adjudication (true)' if not R[(x, y)] else 'reference edge'})
    for x, y in sorted(adj_false - set(R)):
        qs.append({'polarity': 'does_not_have', 'category': 'edge', 'check': {'type': 'edge', 'from': x, 'to': y},
                   'text': f'Does {name(x)} depend on {name(y)} (any edge kind)?', 'source': 'adjudication (false)'})
    for x, y in sorted(R):
        if (y, x) in R or (y, x) in adj_false or kind(y) in ('model', 'external') or kind(x) == 'model':
            continue
        qs.append({'polarity': 'does_not_have', 'category': 'edge', 'check': {'type': 'edge', 'from': y, 'to': x},
                   'text': f'Does {name(y)} {verbs(R[(x, y)])} {name(x)}?', 'source': 'reversal (closed world)'})
    reasons = {}
    for p, rec in sorted(files.items()):
        if (rec or {}).get('owner') == 'out_of_scope' and rec.get('reason'):
            reasons.setdefault(rec['reason'], []).append(p)
    for reason in sorted(reasons):
        qs.append({'polarity': 'does_not_have', 'category': 'scope',
                   'check': {'type': 'files', 'paths': reasons[reason], 'min_share': 0.5},
                   'text': f'Does the graph include, as part of the {subsystem}, the files the reference left out because: "{reason.strip()}"?',
                   'source': f'ownership out_of_scope reason: {reason}'})
    qs += [dict(q) for q in extra]
    out = []
    for i, q in enumerate(qs, 1):
        q = {'id': f'q{i:03d}', **{k: v for k, v in q.items() if k != 'id'}}
        q.setdefault('weight', 1)
        out.append(q)
    return {'status': 'PROVISIONAL', 'reference': label, 'generated': date,
            'notes': 'Draft generated by scoring/make_questions.py; review every question before treating it as final. '
                     'Reversal and scope negatives assume a closed world.',
            'questions': out}


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--reference', required=True)
    ap.add_argument('--ownership', required=True)
    ap.add_argument('--adjudications')
    ap.add_argument('--extra', help='YAML file with hand-written questions (a list, or {questions: [...]})')
    ap.add_argument('--subsystem', default='booking subsystem', help='wording used in scope questions')
    ap.add_argument('--label', help='reference label recorded in the output (default: the --reference path)')
    ap.add_argument('--date', default=datetime.date.today().isoformat())
    ap.add_argument('--out', required=True)
    ap.add_argument('--allow-in-repo', action='store_true', help='allow --out inside the repo for an out-of-repo reference')
    a = ap.parse_args(argv)
    if leaks_into_repo(a.out, a.reference) and not a.allow_in_repo:
        print(f'error: refusing to write answer-key questions to {a.out} inside the team repo; '
              'pick an --out outside it (or pass --allow-in-repo)', file=sys.stderr)
        return 2
    try:
        ref, ownership = load(a.reference), load(a.ownership)
        adj = as_list((load(a.adjudications) or {}).get('pairs')) if a.adjudications else []
        extra = load(a.extra) if a.extra else []
        extra = as_list(extra.get('questions') if isinstance(extra, dict) else extra)
        doc = make(ref, ownership, [x for x in adj if isinstance(x, dict)], extra, a.label or a.reference,
                   a.subsystem, a.date)
    except (InputError, KeyError, TypeError) as ex:
        print(f'error: {ex}', file=sys.stderr)
        return 2
    Path(a.out).parent.mkdir(parents=True, exist_ok=True)
    Path(a.out).write_text(json.dumps(doc, indent=1) + '\n')
    counts = {}
    for q in doc['questions']:
        counts[f"{q['polarity']}/{q['category']}"] = counts.get(f"{q['polarity']}/{q['category']}", 0) + 1
    print(f"wrote {len(doc['questions'])} PROVISIONAL questions to {a.out}: {counts}")
    return 0


if __name__ == '__main__':
    sys.exit(main())
